"""Generate docs/svml-ha-sources.md: every high-accuracy source in the SVML submodule, with its size and
what this repository has for it. Run from the repository root: `make catalog`.

Status is detected from the files present for a function f and precision p (d/s/h):
  functions/f/svml/svml_f_p_ha.c   C translation
  functions/f/avx2/                AVX2 port/variants
  functions/f/hwy/                 Highway version
"""
import os
import re
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SRC = os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512')
PREC = {'d': 'double', 's': 'single', 'h': 'half'}


def source_info(path):
    text = open(path).read()
    lines = text.count('\n')
    consts = len(re.findall(r'^\s*\.(?:long|quad|word|short)\s', text, re.M))
    callout = 'cout_rare_internal' in text
    return lines, consts, callout


def status(func, prec):
    base = os.path.join(ROOT, 'functions', func)
    parts = []
    if os.path.exists(os.path.join(base, 'svml', f'svml_{func}_{prec}_ha.c')):
        parts.append('C translation')
    if prec == 'd':  # the AVX2 and Highway versions are per function; so far double precision only
        if os.path.isdir(os.path.join(base, 'avx2')):
            parts.append('AVX2')
        if os.path.isdir(os.path.join(base, 'hwy')):
            parts.append('Highway')
    return ', '.join(parts)


def main():
    commit = subprocess.run(['git', '-C', os.path.join(ROOT, 'third_party', 'SVML'), 'rev-parse', 'HEAD'],
                            capture_output=True, text=True, check=True).stdout.strip()
    url = f'https://github.com/numpy/SVML/blob/{commit}/linux/avx512'
    files = sorted(f for f in os.listdir(SRC) if f.endswith('_ha.s'))
    entries = {}
    for f in files:
        m = re.fullmatch(r'svml_z0_(\w+?)_([dsh])_ha\.s', f)
        if m:
            entries.setdefault(m.group(1), {})[m.group(2)] = (f, *source_info(os.path.join(SRC, f)))

    out = sys.stdout
    out.write('# SVML high-accuracy sources\n\n')
    out.write('<!-- generated by common/tools/svml_catalog.py (make catalog); do not edit -->\n\n')
    out.write(f'All {len(files)} high-accuracy (`_ha`) sources in the `third_party/SVML` submodule '
              f'([numpy/SVML](https://github.com/numpy/SVML) at `{commit[:7]}`), all AVX-512 (`z0`) assembly. '
              'Size: lines of assembly / data constants (`.long`/`.quad`/...); "callout": has a scalar '
              'routine for special inputs. Status: what this repository has for the source.\n\n')
    done = sum(1 for fn in entries for p in entries[fn] if status(fn, p))
    out.write(f'Studied so far: {done} of {len(files)}.\n\n')
    out.write('| function | precision | source | size | callout | status |\n|---|---|---|---|---|---|\n')
    for fn in sorted(entries):
        link = f'[{fn}](../functions/{fn}/README.md)' if os.path.exists(os.path.join(ROOT, 'functions', fn, 'README.md')) else fn
        for p in ('d', 's', 'h'):
            if p not in entries[fn]:
                continue
            f, lines, consts, callout = entries[fn][p]
            out.write(f'| {link} | {PREC[p]} | [{f}]({url}/{f}) | {lines} / {consts} | {"yes" if callout else "no"} | '
                      f'{status(fn, p)} |\n')


if __name__ == '__main__':
    main()
