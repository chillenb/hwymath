"""Print C declarations for the cbrt_d_ha constants, taken bit-exactly from the SVML assembly."""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', 'svml_z0_cbrt_d_ha.s')
vec = extract(S, '__svml_dcbrt_ha_data_internal_avx512')
sca = extract(S, '__dcbrt_ha__vmldCbrtTab')
hx = lambda q: as_double(q).hex()


def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]


def table(name, off, n, comment):
    print(f'static const double {name}[{n}] = {{  /* {comment} */')
    for j in range(n):
        print(f'    {hx(vec[off // 8 + j])},')
    print('};')


print('/* generated by functions/cbrt/tools/gen_svml_constants.py from svml_z0_cbrt_d_ha.s */')
print('/* vector path (__svml_dcbrt_ha_data_internal_avx512) */')
table('vSh', 0, 8, 'vpermpd table: 2^(j/3) rounded (j = 0, 1, 2), negated copies in 4..6')
table('vSl', 64, 8, 'vpermpd table: 2^(j/3) - vSh[j]')
table('vTh', 128, 16, 'vpermt2pd table: cbrt(16/k) rounded, k = 8..16 (rcp rounded to k/16)')
table('vTl', 256, 16, 'vpermt2pd table: cbrt(16/k) - vTh[k-8]')
for off, name, comment in [(384, 'vShifter', '1.5*2^52: integer in the low mantissa bits'),
                           (512, 'vOneThird', '1/3 rounded up (exponent/3 with an offset of 1/4)'),
                           (576, 'vTwo51', '2^51 = vShifter/3'), (640, 'vThree', '3'), (704, 'vOne', '1'),
                           (1344, 'vC0', 'cbrt(1+R) = 1 + R*(c0 + c1 R + ... + c9 R^9)'),
                           (1280, 'vC1', ''), (1216, 'vC2', ''), (1152, 'vC3', ''), (1088, 'vC4', ''),
                           (1024, 'vC5', ''), (960, 'vC6', ''), (896, 'vC7', ''), (832, 'vC8', ''), (768, 'vC9', '')]:
    c = f'  /* {comment} */' if comment else ''
    print(f'#define {name:<10} {hx(lane(off))}{c}')
print(f'#define vSignMaskBits 0x{lane(448):016x}ULL')
assert len(vec) == 1408 // 8

print('\n/* scalar callout (__dcbrt_ha__vmldCbrtTab) */')
print('static const double sRcp[32] = {  /* ~(1 + i/32)^(-1/3) with 8 significant bits */')
for j in range(32):
    print(f'    {hx(sca[j])},')
print('};')
print('static const double sCbrt2[6] = {  /* {hi (27 bits), lo} of 2^(r/3), r = 0, 1, 2 */')
for j in range(3):
    print(f'    {hx(sca[48 + 2 * j])}, {hx(sca[49 + 2 * j])},')
print('};')
print('static const double sSign[2] = {  /* {1, -1}, indexed by the sign bit */')
print(f'    {hx(sca[55])}, {hx(sca[56])},')
print('};')
names = [(256, 'sTwoThirds', '2/3 rounded'), (264, 'sTwoThirdsLo', '2/3 - sTwoThirds')]
names += [(272 + 8 * i, f'sC{i + 2}', '(1-d)^(-2/3) = 1 + d*(2/3 + d*(c2 + c3 d + ... + c12 d^10))' if i == 0 else '')
          for i in range(11)]
names += [(360, 'sTwo300', '2^300: scales denormal inputs'), (368, 'sSplit27', '2^27 + 1 (Dekker split)'),
          (376, 'sSplit43', '2^43 + 1 (split off 9 bits)'), (432, 'sZero', ''), (440, 'sOne', '')]
for off, name, comment in names:
    c = f'  /* {comment} */' if comment else ''
    print(f'#define {name:<12} {hx(sca[off // 8])}{c}')
assert len(sca) == 456 // 8
