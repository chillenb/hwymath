"""Print C declarations for the exp2_d_ha constants, taken bit-exactly from the SVML assembly."""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', 'svml_z0_exp2_d_ha.s')
vec = extract(S, '__svml_dexp2_ha_data_internal_avx512')
sca = extract(S, '__dexp2_ha__imldExp2HATab')
hx = lambda q: as_double(q).hex()

def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]

print('/* Generated by tools/gen_svml_constants.py from svml_z0_exp2_d_ha.s; do not edit. */')
print('#ifndef SVML_TABLE  /* storage class of the tables (C++ users may define it as static constexpr) */')
print('#define SVML_TABLE static const')
print('#endif')
print('/* vector path (__svml_dexp2_ha_data_internal_avx512) */')
print('SVML_TABLE double vTh[16] = {  /* 2^(j/16), rounded */')
for j in range(16): print(f'    {hx(vec[j])},')
print('};')
print('SVML_TABLE double vTl[16] = {  /* 2^(j/16) - Th[j], rounded */')
for j in range(16): print(f'    {hx(vec[16 + j])},')
print('};')
for off, name in [(256, 'vC1'), (320, 'vC2'), (384, 'vC3'), (448, 'vC4'), (512, 'vC5'), (576, 'vC6'),
                  (640, 'vShifter'), (768, 'vThreshold')]:
    print(f'#define {name:<12} {hx(lane(off))}')
for off, name in [(704, 'vAbsMaskBits'), (832, 'vIndexMaskBits')]:
    print(f'#define {name:<12} 0x{lane(off):016x}ULL')

print('\n/* scalar callout (__dexp2_ha__imldExp2HATab) */')
print('SVML_TABLE double sTab[128] = {  /* {hi, lo} of 2^(j/64), j = 0..63 */')
for j in range(64): print(f'    {hx(sca[2*j])}, {hx(sca[2*j+1])},')
print('};')
for off, name in [(1024, 'sShifter'), (1032, 'sC1'), (1040, 'sC2'), (1048, 'sC3'), (1056, 'sC4'), (1064, 'sC5'),
                  (1072, 'sOverflowX'), (1080, 'sDenormX'), (1088, 'sUnderflowX'), (1096, 'sTiny'), (1104, 'sHuge'),
                  (1112, 'sZero'), (1128, 'sTwo'), (1136, 'sTwoM100')]:
    print(f'#define {name:<12} {hx(sca[off // 8])}')
