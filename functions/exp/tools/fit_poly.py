"""Constants for the faster AVX2 exp (8-entry table, round-to-nearest reduction, degree-7 polynomial).

exp(x) = 2^M * 2^(j/8) * exp(r),  N = M + j/8 = RN(x*log2(e)) to a multiple of 1/8,  |r| <= ln2/16
2^(j/8) = Th[j]*(1 + Tlr[j]);   exp(r) - 1 ~ r*(c1 + c2 r + ... + c7 r^6)

The polynomial minimizes the maximum absolute error of exp(r)-1 on [-h, h] (Lawson's iteratively
reweighted least squares on a Chebyshev grid, 60-digit decimal arithmetic), then is rounded to doubles.
Prints C declarations (hex-float literals) and the fit's error.
"""
from decimal import Decimal as D, getcontext
import math

getcontext().prec = 60
import sys
K = int(sys.argv[1]) if len(sys.argv) > 1 else 3      # table with 2^K entries
DEG = int(sys.argv[2]) if len(sys.argv) > 2 else 7    # coefficients up to r^DEG
# "hp" mode: exp(r) - 1 - r ~ r^2*(c2 + c3 r + ... + c_DEG r^(DEG-2)), for the extra-precision variant
HP = len(sys.argv) > 3 and sys.argv[3] == 'hp'
FIRST = 2 if HP else 1                                # lowest power of r in the polynomial
LN2 = D(2).ln()
H = LN2 / 2 ** (K + 1) * D('1.0005')      # |r| <= ln2/2^(K+1), with a little margin for the rounding of x*log2(e)


def expm1(r):
    term, s, k = r, r, 1
    while abs(term) > D('1e-70'):
        k += 1
        term = term * r / k
        s += term
    return s


def solve(a, b):  # Gaussian elimination with partial pivoting, Decimal
    n = len(b)
    m = [row[:] + [bb] for row, bb in zip(a, b)]
    for c in range(n):
        p = max(range(c, n), key=lambda i: abs(m[i][c]))
        m[c], m[p] = m[p], m[c]
        for i in range(c + 1, n):
            f = m[i][c] / m[c][c]
            for k in range(c, n + 1):
                m[i][k] -= f * m[c][k]
    x = [D(0)] * n
    for i in reversed(range(n)):
        x[i] = (m[i][n] - sum(m[i][k] * x[k] for k in range(i + 1, n))) / m[i][i]
    return x


def fit():
    npts = 400
    pts = [H * D(math.cos(math.pi * (i + 0.5) / npts)) for i in range(npts)] + [H, -H, D(0)]
    f = [expm1(r) - (r if HP else 0) for r in pts]
    nb = DEG - FIRST + 1
    basis = [[r ** (k + FIRST) for k in range(nb)] for r in pts]
    w = [D(1)] * len(pts)
    for _ in range(300):
        ata = [[sum(w[i] * basis[i][a] * basis[i][b] for i in range(len(pts))) for b in range(nb)] for a in range(nb)]
        atb = [sum(w[i] * basis[i][a] * f[i] for i in range(len(pts))) for a in range(nb)]
        c = solve(ata, atb)
        err = [f[i] - sum(c[k] * basis[i][k] for k in range(nb)) for i in range(len(pts))]
        tot = sum(w[i] * abs(err[i]) for i in range(len(pts)))
        w = [w[i] * abs(err[i]) / tot for i in range(len(pts))]
    return c


def max_err(coefs, n=20001):  # error of the polynomial with the *rounded* (double) coefficients
    worst = D(0)
    for i in range(n):
        r = -H + 2 * H * i / (n - 1)
        p = sum(D(coefs[k]) * r ** (k + FIRST) for k in range(len(coefs)))
        worst = max(worst, abs(expm1(r) - (r if HP else 0) - p))
    return worst


if __name__ == '__main__':
    c = [float(v) for v in fit()]
    T = 2 ** K
    th = [float((LN2 * j / T).exp()) for j in range(T)]
    tlr = [float(((LN2 * j / T).exp() - D(t)) / D(t)) for j, t in enumerate(th)]
    P = 'h' if HP else 'f'
    form = f'exp(r)-1-r ~ r^2*(c2 + ... + c{DEG} r^{DEG-2})' if HP else f'exp(r)-1 ~ r*(c1 + ... + c{DEG} r^{DEG-1})'
    print(f'/* generated by functions/exp/tools/fit_poly.py {" ".join(sys.argv[1:])}: {form} on |r| <= ln2/{2**(K+1)},')
    print(f' * max abs error with the rounded coefficients: {max_err(c):.3e} (ulp(1) = 2.2e-16) */')
    print(f'static const double {P}Th[{T}] = {{  /* 2^(j/{T}), rounded */')
    for v in th: print(f'    {v.hex()},')
    print('};')
    print(f'static const double {P}Tlr[{T}] = {{  /* 2^(j/{T}) = Th[j]*(1 + Tlr[j]) */')
    for v in tlr: print(f'    {v.hex()},')
    print('};')
    for k, v in enumerate(c, FIRST):
        print(f'#define {P}C{k} {v.hex()}  /* {v!r} */')
    base = (1023 + 52 - K + 1 - 1) << 52 | 1 << 51  # bits of 1.5*2^(52-K): ulp = 2^-K
    import struct
    s = struct.unpack('<d', struct.pack('<Q', base | (1023 << K)))[0]
    print(f'#define {P}Shifter {s.hex()}  /* 1.5*2^{52-K} (ulp 2^-{K}) + bias 1023 << {K} in the low bits */')
    print(f'#define {P}ShifterBase 0x{base:016x}LL')
    print(f'#define {P}K {K}')
    if HP:  # ln2 = Ln2Hi + Ln2Lo, Ln2Hi with 38 significant bits: N*Ln2Hi/2^K is exact for |N| < 2^14
        hi = float(D(round(LN2 * 2 ** 38)) / 2 ** 38)
        lo = float(LN2 - D(hi))
        print(f'#define hLn2Hi {hi.hex()}  /* ln2 to 38 significant bits */')
        print(f'#define hLn2Lo {lo.hex()}  /* ln2 - hLn2Hi */')
