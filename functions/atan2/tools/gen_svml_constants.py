"""Print C declarations for the atan2_d_ha vector-path constants, taken bit-exactly from the SVML assembly.
(The scalar callout and its table are translated by functions/asin/tools/asm2c.py.)"""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', 'svml_z0_atan2_d_ha.s')
vec = extract(S, '__svml_datan2_ha_data_internal')
ones = extract(S, '.L_2il0floatpacket.40')

def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]

print('/* Generated by tools/gen_svml_constants.py from svml_z0_atan2_d_ha.s (__svml_datan2_ha_data_internal); do not edit. */')
for off, name, what in [
        (192, 'vAtan05Hi', 'atan(1/2) = Atan05Hi + Atan05Lo'), (256, 'vAtan05Lo', ''),
        (320, 'vPio4Hi', 'atan(1) = pi/4'), (384, 'vPio4Lo', ''),
        (448, 'vAtan15Hi', 'atan(3/2)'), (512, 'vAtan15Lo', ''),
        (576, 'vPio2Hi', 'atan(inf) = pi/2'), (640, 'vPio2Lo', ''),
        (704, 'vHalf', '0.5'), (768, 'vOneHalf', '1.5'), (960, 'vPiHi', 'pi (added for x < 0)'),
        (1024, 'vPiLo', 'low part of pi used by the vector path (only ~2e-5 relative accuracy: sic)'),
        (1152, 'vT7_16', 'interval thresholds for |y/x|: 7/16, 19/16, 39/16, 11/16'),
        (1216, 'vT19_16', ''), (1280, 'vT39_16', ''), (1344, 'vT11_16', ''), (1792, 'vOne', '1.0'),
        (2560, 'vC1', 'atan(r) = r + r*R2*(C1 + C2 R2 + ... + C12 R2^11), R2 = r^2'),
        (2496, 'vC2', ''), (2432, 'vC3', ''), (2368, 'vC4', ''), (2304, 'vC5', ''), (2240, 'vC6', ''),
        (2176, 'vC7', ''), (2112, 'vC8', ''), (2048, 'vC9', ''), (1984, 'vC10', ''), (1920, 'vC11', ''),
        (1856, 'vC12', ''), (2880, 'vZero', '0.0'), (3072, 'vZPi', 'zero-argument branch: pi, pi/2'),
        (3136, 'vZPio2', '')]:
    q = lane(off)
    print(f'#define {name:<10} {as_double(q).hex():<26}/* {what} */' if what else f'#define {name:<10} {as_double(q).hex()}')
for off, name in [(896, 'vAbsMaskBits'), (832, 'vSignMaskBits')]:
    print(f'#define {name} 0x{lane(off):016x}ULL')
# high-word range check on 32-bit lanes: (int32)(hi(|v|) - vHiBase) >= (int32)vHiLimit: hi < 0x00300000 or hi >= 0x7e000000
for off, name in [(2688, 'vHiBase'), (2752, 'vHiLimit')]:
    q = lane(off)
    assert q & 0xffffffff == q >> 32
    print(f'#define {name} 0x{q & 0xffffffff:08x}u')
assert ones == [0xffffffffffffffff]
