"""Print C declarations for the expm1_d_ha constants, taken bit-exactly from the SVML assembly."""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', 'svml_z0_expm1_d_ha.s')
vec = extract(S, '__svml_dexpm1_ha_data_internal_avx512')
sca = extract(S, '_imldExpHATab')  # local symbol; same contents as exp's table of the same name
hx = lambda q: as_double(q).hex()

def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]

print('/* Generated by tools/gen_svml_constants.py from svml_z0_expm1_d_ha.s; do not edit. */')
print('#ifndef SVML_TABLE  /* storage class of the tables (C++ users may define it as static constexpr) */')
print('#define SVML_TABLE static const')
print('#endif')
print('/* vector path (__svml_dexpm1_ha_data_internal_avx512) */')
print('SVML_TABLE double vTh[16] = {  /* 2^(j/16), rounded */')
for j in range(16): print(f'    {hx(vec[j])},')
print('};')
print('SVML_TABLE double vTlr[16] = {  /* 2^(j/16) = Th[j] * (1 + Tlr[j]) */')
for j in range(16): print(f'    {hx(vec[16 + j])},')
print('};')
for off, name in [(256, 'vLog2e'), (320, 'vShifter'), (384, 'vThreshold'), (512, 'vLn2Hi'), (576, 'vLn2Lo'),
                  (640, 'vMinN'), (768, 'vC8'), (832, 'vC7'), (896, 'vC6'), (960, 'vC5'), (1024, 'vC4'),
                  (1088, 'vC3'), (1152, 'vC2'), (1216, 'vOne'), (1280, 'vMinusOne')]:
    print(f'#define {name:<12} {hx(lane(off))}')
for off, name in [(448, 'vSignMaskBits'), (704, 'vRMaskBits')]:
    print(f'#define {name:<12} 0x{lane(off):016x}ULL')

print('\n/* scalar callout (_imldExpHATab) */')
print('SVML_TABLE double sTab[128] = {  /* {hi, lo} of 2^(j/64), j = 0..63 */')
for j in range(64): print(f'    {hx(sca[2*j])}, {hx(sca[2*j+1])},')
print('};')
for off, name in [(1024, 's64OverLn2'), (1032, 'sShifter'), (1040, 'sC2'), (1048, 'sC3'), (1056, 'sC4'), (1064, 'sC5'),
                  (1072, 'sC6'), (1080, 'sOverflowX'), (1088, 'sDenormX'), (1096, 'sUnderflowX'), (1104, 'sLn2o64Hi'),
                  (1112, 'sLn2o64Lo'), (1120, 'sTiny'), (1128, 'sHuge'), (1136, 'sZero'), (1144, 'sOne'),
                  (1152, 'sTwo'), (1160, 'sTwoM60'), (1168, 'sSplitter')]:
    print(f'#define {name:<12} {hx(sca[off // 8])}')
