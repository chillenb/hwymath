"""Print C declarations for the asin_d_ha vector-path constants, taken bit-exactly from the SVML assembly.
(The scalar callout and its table are translated by asm2c.py.)"""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', 'svml_z0_asin_d_ha.s')
vec = extract(S, '__svml_dasin_ha_data_internal')

def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]

print('/* Generated by tools/gen_svml_constants.py from svml_z0_asin_d_ha.s (__svml_dasin_ha_data_internal); do not edit. */')
for off, name, what in [
        (64, 'vHalf', '0.5'), (128, 'vSmallY', '2^-255: rsqrt approximation set to 0 below this'),
        (256, 'vOne', '1.0: |x| > 1 takes the callout'), (384, 'vTwo', '2.0'),
        (448, 'vSqrtC3', 'sqrt correction: 2 sqrt(Y) = Sh + Sh*e*(C0 + C1 e + C2 e^2 + C3 e^3) - Sh_err'),
        (512, 'vSqrtC2', ''), (576, 'vSqrtC1', ''), (640, 'vSqrtC0', ''),
        (704, 'vC12', 'asin(s) = s + s*R*(C1 + C2 R + ... + C12 R^11), R = s^2'),
        (768, 'vC11', ''), (832, 'vC10', ''), (896, 'vC9', ''), (960, 'vC8', ''), (1024, 'vC7', ''),
        (1088, 'vC6', ''), (1152, 'vC5', ''), (1216, 'vC4', ''), (1280, 'vC3', ''), (1344, 'vC2', ''),
        (1408, 'vC1', ''), (1472, 'vPio2Hi', 'pi/2 = Pio2Hi + Pio2Lo'), (1536, 'vPio2Lo', ''), (1600, 'vZero', '')]:
    q = lane(off)
    print(f'#define {name:<10} {as_double(q).hex():<26}/* {what} */' if what else f'#define {name:<10} {as_double(q).hex()}')
print(f'#define vAbsMaskBits 0x{lane(0):016x}ULL')
