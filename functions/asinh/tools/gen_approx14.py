ALPHA = (20.5, 46.5)  # rsqrt: curvature term for [1, 2) and [2, 4)
BETA = -2.0
DK = (512.0, 1024.0)


def fma(a, b, c):  # correctly rounded a*b + c
    return float(Fr(a) * Fr(b) + Fr(c))


def pack(res):  # 64 values 0..15 -> four words of 16 nibbles
    assert len(res) == 64 and all(0 <= r <= 15 for r in res), res
    return [sum(res[16 * w + k] << (4 * k) for k in range(16)) for w in range(4)]


ra = []
for i in range(64):
    b, a = RCP14_COEFF[2 * i], RCP14_COEFF[2 * i + 1]
    y = (129 + 2 * i) / 128
    q = 1.0 / y
    assert fma(math.floor((q * q) * 512.0), 512.0, 256.0) == 256 * b, i
    ra.append(a - math.floor(q * 262144.0))
rc = []
for h in range(2):
    for i in range(32):
        d, c = RSQRT14_COEFF[4 * i + 2 * h], RSQRT14_COEFF[4 * i + 2 * h + 1]
        y = (65 + 2 * i) / 64 * (1 + h)
        q = 1.0 / math.sqrt(y)
        q2 = q * q
        q3 = q2 * q
        q5 = q3 * q2
        assert fma(math.floor(q3 * DK[h]), 512.0, 256.0) == 256 * d, (h, i)
        rc.append(c - math.floor(fma(q, 524288.0, fma(ALPHA[h], q5, BETA))))

