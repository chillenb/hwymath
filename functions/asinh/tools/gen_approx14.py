"""Generate functions/asinh/hwy/approx14_tables.h: the data for the exact emulation of VRCP14PD/VRSQRT14PD
(double precision) in hwy/approx14-inl.h.

The instructions are defined bit-exactly by Intel's reference implementation RECIP14.c ("Reference
Implementations for IA Approximation Instructions VRCP14, VRSQRT14, VRCP28, VRSQRT28, and VEXP2",
https://www.intel.com/content/www/us/en/developer/articles/code-sample/reference-implementations-for-ia-approximation-instructions-vrcp14-vrsqrt14-vrcp28-vrsqrt28-vexp2.html,
Copyright (c) 2015 Intel Corporation, BSD-3-Clause; the coefficient tables below are copied from it). For a
mantissa in [1, 2) (rcp14) or [1, 4) (rsqrt14) they evaluate a linear function on one of 64 segments,
    rcp14:   r = a[i] - 256*b[i]*(xt - y[i]),  y[i] = 1 + (2i + 1)/128,       result trunc17(r)*2^-18
    rsqrt14: r = c[i] - 256*d[i]*(xt - y[i]),  y[i] = 1 + (2i + 1)/64 (x2),   result trunc17(r)*2^-19
with xt = x truncated to 17 (rsqrt: 16) significant bits; all of it is exact in double precision.

A 64-entry table lookup is slow without gathers, so the vector code computes the coefficients instead:
    b = 2*floor(512/y^2) + 1                     (= floor(1024/y^2) | 1; checked below for every segment)
    d = 2*floor(K/y^1.5) + 1,  K = 512 on [1, 2), 1024 on [2, 4)
    a = floor(2^18/y) + ra[i]
    c = floor(2^19/sqrt(y) + alpha*y^-2.5 - 2) + rc[i],  alpha = 20.5 on [1, 2), 46.5 on [2, 4)
with small corrections ra, rc in 0..15 stored as 4-bit fields of four 64-bit words. The script simulates the
vector code's double operations (same order; FMAs rounded once via exact rationals), so the corrections are
exact for that code; tests/test_approx14 checks the emulation against the reference for every coefficient.
"""
