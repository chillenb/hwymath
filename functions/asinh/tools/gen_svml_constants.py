"""Print C declarations for the asinh_d_ha (and acosh_d_ha) constants, taken bit-exactly from the SVML assembly.

usage: gen_svml_constants.py ASM_FILE [asinh|acosh]
The data layouts of svml_z0_asinh_d_ha.s and svml_z0_acosh_d_ha.s are identical (same offsets, same values
except the small-input threshold at offset 384); functions/acosh/tools/gen_svml_constants.py reuses this script.
"""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

F = sys.argv[2] if len(sys.argv) > 2 else 'asinh'
S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', f'svml_z0_{F}_d_ha.s')
vec = extract(S, f'__svml_d{F}_ha_data_internal_avx512')
hx = lambda q: as_double(q).hex() if (q >> 52) & 0x7ff != 0x7ff else None

def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]

print(f'/* generated by functions/asinh/tools/gen_svml_constants.py from svml_z0_{F}_d_ha.s */')
print(f'/* vector path (__svml_d{F}_ha_data_internal_avx512) */')
print('static const double kLogTh[16] = {  /* -log(1 + k/16), high part (k = top 4 mantissa bits of Rcp) */')
for j in range(16): print(f'    {hx(vec[j])},')
print('};')
print('static const double kLogTl[16] = {  /* low part */')
for j in range(16): print(f'    {hx(vec[16 + j])},')
print('};')
A = F == 'asinh'
dbl = [(256, 'kOne', ''),
       (384, 'kSmallX', ('|x|' if A else 'x^2 - 1') + ' below this: small-input polynomial'),
       (448, 'kLargeX', 'from here: log(x*LargeScale) + LargeK*ln2, no square root'),
       (512, 'kMaxX', ('|x| > this or NaN' if A else 'x > this, x <= 1 or NaN') + ': scalar callout'),
       (576, 'kSmallC3', 'small inputs: asinh(s) = s + s^3*(C1 + C2 s^2 + C3 s^4)' + ('' if A else ', s = sqrt(x^2 - 1)')), (640, 'kSmallC2', ''), (704, 'kSmallC1', ''),
       (768, 'kSqrtC4', 'sqrt refinement: poly_s(Eh) = C1 + C2 Eh + C3 Eh^2 + C4 Eh^3'), (832, 'kSqrtC3', ''),
       (896, 'kSqrtC2', ''), (960, 'kSqrtC1', ''),
       (1280, 'kLargeScale', ''), (1344, 'kLargeK', ''),
       (1408, 'kLogC9', 'log(1+R) = R + R^2*(C1 + C2 R + ... + C9 R^8)'), (1472, 'kLogC8', ''), (1536, 'kLogC7', ''),
       (1600, 'kLogC6', ''), (1664, 'kLogC5', ''), (1728, 'kLogC4', ''), (1792, 'kLogC3', ''), (1856, 'kLogC2', ''),
       (1920, 'kLogC1', ''), (1984, 'kL2H', 'ln2 = L2H + L2L'), (2048, 'kL2L', '')]
for off, name, comment in dbl:
    c = f'  /* {comment} */' if comment else ''
    print(f'static const double {name} = {hx(lane(off))};{c}')
for off, name, comment in [(320, 'kAbsMask', ''), (1152, 'kRcpRoundAdd', 'Rcp: rcp14 rounded to 1+4 mantissa bits'),
                           (1216, 'kRcpRoundMask', '')]:
    c = f'  /* {comment} */' if comment else ''
    print(f'static const uint64_t {name} = 0x{lane(off):016x}ULL;{c}')
# unused by the code: offsets 1024, 1088, 2112 (0.375, 0.5, 0.5)
for off in (1024, 1088, 2112):
    assert as_double(lane(off)) in (0.375, 0.5)

cout = extract(S, f'__d{F}_ha_CoutTab') if F == 'acosh' else None
if cout:
    print(f'\n/* scalar callout (__d{F}_ha_CoutTab) */')
    print('static const double kCoutTab[4] = {', ', '.join(hx(q) or ('INFINITY' if q >> 63 == 0 else '-INFINITY') for q in cout), '};')
