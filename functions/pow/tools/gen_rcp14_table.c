/* Derives the rounding behaviour of the vector pow's reciprocal, rndscale(vrcp14pd(m), 5 fraction bits,
 * round to nearest), for all mantissas m in [1/2, 1), and prints it as the switch-point table used by the
 * Highway version (hwy/rcp14_switch.inc). Needs AVX-512F (run under Intel SDE otherwise).
 *
 * Intel's reference implementation of VRCP14 (recip14.c, "Reference Implementations for IA Approximation
 * Instructions") computes the double-precision result from the leading 16 fraction bits of the input only
 * (the low 36 bits are cleared before a table-driven linear interpolation); exact powers of two get exact
 * reciprocals. This program checks that property (every 16-bit prefix: lowest, highest and random members
 * must give the same vrcp14pd result, except m = 1/2 which is a power of two), then enumerates the 2^16
 * prefixes: the rounded value must be non-increasing in m, so it is described by 32 switch points.
 * Exit status != 0 if a check fails. */
#include <immintrin.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static uint64_t s = 0x9e3779b97f4a7c15ULL;
static uint64_t rnd(void) { s ^= s << 13; s ^= s >> 7; s ^= s << 17; return s; }
static double bd(uint64_t u) { double d; memcpy(&d, &u, 8); return d; }
static uint64_t db(double d) { uint64_t u; memcpy(&u, &d, 8); return u; }

__attribute__((target("avx512f"))) static void
rcp(double m, uint64_t *raw, double *rounded)
{
    double r[8], q[8];
    const __m512d v = _mm512_rcp14_pd(_mm512_set1_pd(m));
    _mm512_storeu_pd(r, v);
    _mm512_storeu_pd(q, _mm512_roundscale_round_pd(v, 0x58, _MM_FROUND_NO_EXC));
    *raw = db(r[0]);
    *rounded = q[0];
}

int
main(void)
{
    if (!__builtin_cpu_supports("avx512f")) {
        fprintf(stderr, "gen_rcp14_table: needs AVX-512F (run under Intel SDE)\n");
        return 77;
    }
    static double G[65536];
    size_t bad = 0, members = 0;
    for (uint64_t p = 0; p < 65536; p++) {
        const uint64_t base = 0x3fe0000000000000ULL | (p << 36);
        uint64_t r0 = 0;
        for (int t = 0; t < 64; t++) {
            const uint64_t low = t == 0 ? 1 : t == 1 ? (1ULL << 36) - 1 : t == 2 ? 1ULL << 35 : rnd() & ((1ULL << 36) - 1);
            uint64_t raw;
            double g;
            rcp(bd(base | low), &raw, &g);
            members++;
            if (t == 0) { r0 = raw; G[p] = g; }
            else if (raw != r0 || db(g) != db(G[p])) bad++;
        }
    }
    uint64_t raw;
    double g_half;
    rcp(0.5, &raw, &g_half);
    if (g_half != G[0]) bad++;
    int switches = 0;
    unsigned sw[32];
    for (int p = 1; p < 65536; p++) {
        if (G[p] > G[p - 1] || (G[p] != G[p - 1] && G[p - 1] - G[p] != 1.0 / 32)) bad++;
        if (G[p] != G[p - 1]) {
            if (switches < 32 && G[p] * 32 == 63 - switches) sw[31 - switches] = (unsigned)p;
            else bad++;
            switches++;
        }
    }
    if (switches != 32 || G[0] != 2.0 || G[65535] != 1.0) bad++;
    fprintf(stderr, "gen_rcp14_table: %zu mantissas checked, %d switch points, %zu violations\n", members, switches, bad);
    if (bad) return 1;
    printf("/* Generated by tools/gen_rcp14_table.c (under Intel SDE): rcp = rndscale(vrcp14pd(m), 1/32, RN) for\n"
           " * m in [1/2, 1) depends only on the 16-bit prefix p = top 16 fraction bits of m. Entry i (k = 32 + i):\n"
           " * rcp = (k+1)/32 for p < POW_RCP14_SWITCH[i] and rcp <= k/32 from there on (non-increasing in p). */\n");
    printf("#define POW_RCP14_SWITCH_PREFIXES \\\n   ");
    for (int i = 0; i < 32; i++) printf(" 0x%04x%s%s", sw[i], i < 31 ? "," : "", i % 8 == 7 && i < 31 ? " \\\n   " : "");
    printf("\n");
    return 0;
}
