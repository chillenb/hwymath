"""Print C declarations for the constants of SVML's log, log2, log10 or log1p (double, HA), taken bit-exactly
from the assembly. Shared by functions/{log,log2,log10,log1p}.

usage: gen_svml_constants.py FUNCTION [ASM_FILE] [--cxx]     (FUNCTION = log, log2, log10 or log1p)
  --cxx: only the vector-path constants, as C++ constexpr (kTh, kTl, kC9, ...) for the Highway version"""
import os, struct, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

CXX = '--cxx' in sys.argv
args = [a for a in sys.argv[1:] if a != '--cxx']
F = args[0]
S = args[1] if len(args) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', f'svml_z0_{F}_d_ha.s')
vec = extract(S, f'__svml_d{F}_ha_data_internal_avx512')
def hx(q):
    d = as_double(q)
    return d.hex() if d == d and abs(d) != float('inf') else ('INFINITY' if d > 0 else '-INFINITY')

def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]

# vector constants: offset -> name, per function. cN = coefficient of R^N of the polynomial (see the .c files)
VEC = {
    'log':   {256: 'vOne', 320: 'vThree4', 384: 'vC9', 448: 'vC8', 512: 'vC7', 576: 'vC6', 640: 'vC5', 704: 'vC4',
              768: 'vC3', 832: 'vC2', 896: 'vL2H', 960: 'vL2L'},
    'log2':  {256: 'vOne', 320: 'vThree4', 384: 'vC10', 448: 'vC9', 512: 'vC8', 576: 'vC7', 640: 'vC6', 704: 'vC5',
              768: 'vC4', 832: 'vC3', 896: 'vC2', 960: 'vC1L', 1024: 'vC1H'},
    'log10': {256: 'vOne', 320: 'vThree4', 384: 'vC9', 448: 'vC8', 512: 'vC7', 576: 'vC6', 640: 'vC5', 704: 'vC4',
              768: 'vC3', 832: 'vC2', 896: 'vC1L', 960: 'vC1H', 1024: 'vL2H', 1088: 'vL2L'},
    'log1p': {256: 'vOne', 320: 'vSignMask', 384: 'vThree4', 448: 'vC9', 512: 'vC8', 576: 'vC7', 640: 'vC6',
              704: 'vC5', 768: 'vC4', 832: 'vC3', 896: 'vC2', 960: 'vL2H', 1024: 'vL2L'},
}[F]

print(f'/* Generated by functions/log/tools/gen_svml_constants.py {F}{" --cxx" if CXX else ""} from svml_z0_{F}_d_ha.s; do not edit. */')
if CXX:
    print('constexpr double kTh[16] = {' + ', '.join(hx(vec[j]) for j in range(16)) + '};')
    print('constexpr double kTl[16] = {' + ', '.join(hx(vec[16 + j]) for j in range(16)) + '};')
    for off, name in VEC.items():
        if name == 'vSignMask':
            print(f'constexpr uint64_t kSignMask = 0x{lane(off):016x}ULL;')
        else:
            print(f'constexpr double k{name[1:]} = {hx(lane(off))};')
    sys.exit(0)
print(f'/* vector path (__svml_d{F}_ha_data_internal_avx512) */')
print('static const double vTh[16] = {  /* high parts of -log_b(rcp) (of -log_b(2 rcp) for rcp < 0.75); index: top 4 mantissa bits of rcp */')
for j in range(16): print(f'    {hx(vec[j])},')
print('};')
print('static const double vTl[16] = {  /* low parts */')
for j in range(16): print(f'    {hx(vec[16 + j])},')
print('};')
for off, name in VEC.items():
    if name == 'vSignMask':
        print(f'#define {name:<10} 0x{lane(off):016x}ULL')
    else:
        print(f'#define {name:<10} {hx(lane(off))}')

if F in ('log', 'log10', 'log1p'):
    tab = extract(S, f'__d{F}_ha_CoutTab')
    n = 1560 // 8
    print(f'\n/* scalar callout (__d{F}_ha_CoutTab) */')
    print(f'static const double sTab[{n}] = {{  /* {{rcp, -log_b(rcp) high, low}} x {n // 3} */')
    for j in range(n // 3): print(f'    {hx(tab[3*j])}, {hx(tab[3*j+1])}, {hx(tab[3*j+2])},')
    print('};')
    names = {1560: 'sL2H', 1568: 'sL2L', 1576: 'sIdxShifter', 1584: 'sRndShifter', 1592: 'sNear1', 1600: 'sTwo60',
             1608: 'sZero', 1616: 'sOne'}
    for off, name in names.items(): print(f'#define {name:<12} {hx(tab[off // 8])}')
    first = 1624 if F != 'log10' else 1632
    if F == 'log10': print(f'#define {"sScale":<12} {hx(tab[1624 // 8])}')
    for i, off in enumerate(range(first, len(tab) * 8, 8)):
        print(f'#define {"sP%d" % i:<12} {hx(tab[off // 8])}')
    print(f'#define {"sPacketOne":<12} 0x1p+0  /* .L_2il0floatpacket (1.0) */')
else:  # log2: libm-style callout
    print('\n/* scalar callout (log2) */')
    def arr(sym, cnt=None):
        w = extract(S, sym)
        return w if cnt is None else w[:cnt]
    for sym, name in [('_zeros.402.0.0.1', 'sZeros'), ('_ones.402.0.0.1', 'sOnes'), ('_infs.402.0.0.1', 'sInfs')]:
        w = arr(sym)
        print(f'static const double {name}[2] = {{{hx(w[0])}, {hx(w[1])}}};')
    for sym, name, cnt in [('__dlog2_ha__Q3', 'sQ3', 4), ('__dlog2_ha__Q2', 'sQ2', 5), ('__dlog2_ha__Q1', 'sQ1', 12),
                           ('__dlog2_ha__P', 'sP', 7)]:
        w = arr(sym, cnt)
        print(f'static const double {name}[{cnt}] = {{' + ', '.join(hx(q) for q in w) + '};')
    for sym, name in [('__dlog2_ha__TWO_32P', 'sTwo32P'), ('__dlog2_ha__TWO_32', 'sTwo32'), ('__dlog2_ha__TWO_55', 'sTwo55')]:
        print(f'#define {name:<8} {hx(arr(sym, 1)[0])}')
    w = arr('__dlog2_ha___libm_rcp_table_256', 128)
    f32 = [x for q in w for x in (q & 0xffffffff, q >> 32)]
    print('static const float sRcp256[256] = {')
    for i in range(0, 256, 4):
        print('    ' + ' '.join(f'{struct.unpack("<f", struct.pack("<I", v))[0].hex()}f,' for v in f32[i:i + 4]))
    print('};')
    w = arr('__dlog2_ha___libm_log2_table_256', 512)
    print('static const double sLog2Tab[512] = {  /* {low, high} of -log2(rcp) */')
    for i in range(0, 512, 2): print(f'    {hx(w[i])}, {hx(w[i+1])},')
    print('};')
