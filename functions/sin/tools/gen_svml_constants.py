"""Print C/C++ declarations of the constants of SVML's high-accuracy double sin or cos (svml_z0_sin_d_ha.s,
svml_z0_cos_d_ha.s; both have the same data layout), or of the large-argument reduction data shared by
sin, cos and tan, taken bit-exactly from the assembly.

usage: gen_svml_constants.py sin|cos [ASM]      constants of __svml_d<f>_ha_data_internal{,_ha}
       gen_svml_constants.py reduction [ASM]    __svml_dsin_ha_reduction_data_internal and the
                                                reduction constants (.L_2il0floatpacket.*)
The declarations use HWYMATH_CONST (static const in C, static constexpr in C++), so the same file
serves the C translation and the Highway version."""
import os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

f = sys.argv[1]
S = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    ROOT, 'third_party', 'SVML', 'linux', 'avx512', f'svml_z0_{"sin" if f == "reduction" else f}_d_ha.s')
hx = lambda q: as_double(q).hex() if (q >> 52) & 0x7ff != 0x7ff else None

guard = 'SVML_TRIG_REDUCTION_DATA_INC' if f == 'reduction' else f'SVML_{f.upper()}_D_HA_CONSTANTS_INC'
print(f'/* generated by functions/sin/tools/gen_svml_constants.py {f} from {os.path.basename(S)}; do not edit */')
print(f'#ifndef {guard}\n#define {guard}')
print('#ifndef HWYMATH_CONST\n#ifdef __cplusplus\n#define HWYMATH_CONST static constexpr\n#else\n'
      '#define HWYMATH_CONST static const __attribute__((unused))\n#endif\n#endif\n#include <stdint.h>\n')

def lanes(words, off, name):  # 64-byte block of 8 identical lanes
    w = words[off // 8: off // 8 + 8]
    assert len(set(w)) == 1, (name, off)
    return w[0]

def dconst(name, q, comment=''):
    c = f'  /* {comment} */' if comment else ''
    print(f'HWYMATH_CONST double {name} = {hx(q)};{c}')

def uconst(name, q, comment=''):
    c = f'  /* {comment} */' if comment else ''
    print(f'HWYMATH_CONST uint64_t {name} = 0x{q:016x}ULL;{c}')

if f == 'reduction':
    red = extract(S, '__svml_dsin_ha_reduction_data_internal')
    assert len(red) == 3 * 2048
    src = open(S).read()
    fp = {int(n): int(hi, 16) << 32 | int(lo, 16)
          for n, lo, hi in re.findall(r'\n\.L_2il0floatpacket\.(\d+):\n\t\.long\t(0x[0-9a-f]+),(0x[0-9a-f]+)\n', src)}
    print('/* constants of the large-argument path (.L_2il0floatpacket.27-43 of svml_z0_sin_d_ha.s) */')
    names = [(27, 'AllOnes', 'u'), (28, 'ExpMask', 'u'), (29, 'MantMask', 'u'), (30, 'ImplicitBit', 'u'),
             (31, 'Low32', 'u'), (32, 'SignMask', 'u'), (33, 'OneBits', 'u'), (34, 'Shifter', 'd'),
             (35, 'Mask9', 'u'), (36, 'Two104Bits', 'u'), (37, 'Low24', 'u'), (38, 'Two52Bits', 'u'),
             (39, 'Low12', 'u'), (40, 'TwoPiHi', 'd'), (41, 'TwoPiLo', 'd'), (42, 'AbsMask', 'u'),
             (43, 'Tiny', 'd')]
    comments = {'Shifter': '2^43 + 2^42: rounds to multiples of 2^-9', 'Two104Bits': '2^-104',
                'Two52Bits': '2^-52', 'TwoPiHi': '2*pi = TwoPiHi + TwoPiLo', 'TwoPiLo': '',
                'Tiny': '2^-20: smaller |x| pass through unreduced', 'ImplicitBit': '2^52',
                'OneBits': '1.0'}
    for n, name, t in names:
        (dconst if t == 'd' else uconst)(f'trig_red_{name}', fp[n], comments.get(name, ''))
    print('\n/* __svml_dsin_ha_reduction_data_internal (identical in the sin, cos and tan sources): for each')
    print(' * biased exponent e, three 64-bit words of the bits of 2/pi scaled for that exponent */')
    print('HWYMATH_CONST uint64_t trig_red_Tab[6144] = {')
    for e in range(2048):
        print('    ' + ', '.join(f'0x{q:016x}ULL' for q in red[3 * e: 3 * e + 3]) + ',')
    print('};\n#endif')
    sys.exit(0)

v = extract(S, f'__svml_d{f}_ha_data_internal')
h = extract(S, f'__svml_d{f}_ha_data_internal_ha')
P = f'{f}_'
print(f'/* main path (__svml_d{f}_ha_data_internal): x = N*pi/16 + R, 16-entry tables indexed by N mod 16 */')
for off, name, cm in [(0, 'AbsMask', ''), (64, 'RangeVal', 'larger |x| (and NaN): large-argument path'),
                      (128, 'InvPi', '16/pi'), (192, 'RShift', '1.5*2^52'),
                      (256, 'PI1', 'pi/16 = PI1 + PI2 + PI3'), (320, 'PI2', ''), (384, 'PI3', '')]:
    (uconst if name == 'AbsMask' else dconst)(P + 'v' + name, lanes(v, off, name), cm)
for off, name, cm in [(512, 'Sh', 'sin(j*pi/16)'), (640, 'Ch', 'cos(j*pi/16)')]:
    print(f'HWYMATH_CONST double {P}v{name}[16] = {{  /* {cm} */')
    print('    ' + ', '.join(hx(q) for q in v[off // 8: off // 8 + 16]) + ',\n};')
print(f'HWYMATH_CONST uint64_t {P}vClSl[16] = {{  /* Cl = low part of cos (as a double), Sl = its low 32 bits << 32 */')
print('    ' + ', '.join(f'0x{q:016x}ULL' for q in v[768 // 8: 768 // 8 + 16]) + ',\n};')
if f == 'sin':
    uconst(P + 'vMinusZero', lanes(v, 896, 'mz'), '-0.0: sets the sign of sin(-0)')
    uconst(P + 'vZeroSignBit', lanes(v, 960, 'zs'), 'xored into N for x = -0')
    c0 = 1024
else:
    c0 = 896
# cos(z) - 1 ~ z^2 (C1 + C2 z^2 + C3 z^4 + C4 z^6), sin(z) - z ~ z^3 (S1 + S2 z^2 + S3 z^4 + S4 z^6)
for k, name in enumerate(['C4', 'C3', 'S4', 'S3', 'C2', 'S2', 'C1', 'S1']):
    dconst(P + 'v' + name, lanes(v, c0 + 64 * k, name))

print(f'\n/* large-argument path (__svml_d{f}_ha_data_internal_ha): x = M*pi/256 + r, 512 entries')
print(' * {T0, T1, T2, T3} per M mod 512 (see the C translation for their use) */')
print(f'HWYMATH_CONST double {P}hT[2048] = {{')
for j in range(512):
    print('    ' + ', '.join(hx(q) for q in h[4 * j: 4 * j + 4]) + ',')
print('};')
for off, name in [(16960, 'S1'), (17024, 'S2'), (17088, 'C1'), (17152, 'C2'), (17216, 'C3')]:
    dconst(P + 'h' + name, lanes(h, off, name))
uconst(P + 'hExpMask', lanes(h, 16512, 'ExpMask'), 'exponent bits: inf/NaN test')
print('#endif')
