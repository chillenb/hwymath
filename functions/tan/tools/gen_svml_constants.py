"""Print C/C++ declarations of the constants of SVML's high-accuracy double tan (svml_z0_tan_d_ha.s), taken
bit-exactly from the assembly. The large-argument reduction table and its constants are identical to
those of sin (functions/sin/svml/svml_trig_reduction_data.inc); this script checks that.

usage: gen_svml_constants.py [ASM]"""
import os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

A = os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512')
S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(A, 'svml_z0_tan_d_ha.s')
hx = lambda q: as_double(q).hex() if (q >> 52) & 0x7ff != 0x7ff else None

def floatpackets(path):
    src = open(path).read()
    return [(int(n), [int(w, 16) for w in ws.split(',')])
            for n, ws in re.findall(r'\n\.L_2il0floatpacket\.(\d+):\n\t\.long\t([0-9a-fx,]+)\n', src)]

# the large-argument reduction must be the one of sin
sin_s = os.path.join(A, 'svml_z0_sin_d_ha.s')
assert extract(S, '__svml_dtan_ha_reduction_data_internal') == extract(sin_s, '__svml_dsin_ha_reduction_data_internal')
fp_tan = {n: w for n, w in floatpackets(S)}
fp_sin = {n: w for n, w in floatpackets(sin_s)}
assert [fp_tan[n] for n in range(18, 35)] == [fp_sin[n] for n in range(27, 44)]
assert fp_tan[35] == [8] * 8
q64 = lambda w: w[1] << 32 | w[0]

print(f'/* generated by functions/tan/tools/gen_svml_constants.py from {os.path.basename(S)}; do not edit */')
print('#ifndef HWYMATH_CONST\n#ifdef __cplusplus\n#define HWYMATH_CONST static constexpr\n#else\n'
      '#define HWYMATH_CONST static const __attribute__((unused))\n#endif\n#endif\n#include <stdint.h>\n')

v = extract(S, '__svml_dtan_ha_data_internal')

def lanes(off, name):
    w = v[off // 8: off // 8 + 8]
    assert len(set(w)) == 1, (name, off)
    return w[0]

def dconst(name, q, comment=''):
    c = f'  /* {comment} */' if comment else ''
    print(f'HWYMATH_CONST double {name} = {hx(q)};{c}')

print('/* main path (__svml_dtan_ha_data_internal): x = N*pi/16 + R, |R| <= pi/32 */')
for off, name, cm in [(0, 'InvPi', '16/pi'), (1152, 'RShift', '1.5*2^52'), (64, 'PI1', 'pi/16 = PI1 + PI2 + PI3'),
                      (256, 'PI2', ''), (320, 'PI3', ''),
                      (28160, 'RangeVal', 'larger |x| (and NaN): large-argument path')]:
    dconst('tan_v' + name, lanes(off, name), cm)
for off, name, cm in [(384, 'Th', 'tan(j*pi/16) rounded; j = 8: -DBL_MAX'),
                      (512, 'Tl', 'tan(j*pi/16) - Th[j]; j = 8: -2^971')]:
    print(f'HWYMATH_CONST double tan_v{name}[16] = {{  /* {cm} */')
    print('    ' + ', '.join(hx(q) for q in v[off // 8: off // 8 + 16]) + ',\n};')
print('/* (tan R - R)/R^3 ~ P1 + P2 R^2 + ... + P5 R^8 */')
for k in range(5):
    dconst(f'tan_vP{k + 1}', lanes(640 + 64 * k, f'P{k + 1}'))
dconst('tan_vOne', lanes(960, 'One'))
print(f'HWYMATH_CONST uint64_t tan_vAbsMask = 0x{lanes(1024, "AbsMask"):016x}ULL;')
print(f'HWYMATH_CONST uint64_t tan_vExpMask = 0x{lanes(1088, "ExpMask"):016x}ULL;  /* inf/NaN test */')
print('\n/* large-argument path (.L_2il0floatpacket.35-37): x = M*pi/256 + r, M = 16*k + j, |j| <= 8 */')
dconst('tan_lPi256Hi', q64(fp_tan[36]), 'pi/256 = Pi256Hi + Pi256Lo')
dconst('tan_lPi256Lo', q64(fp_tan[37]))
print('HWYMATH_CONST uint32_t tan_lHalf = 8;  /* rounds M/16 to nearest */')
