"""Print C declarations for the atanh_d_ha constants, taken bit-exactly from the SVML assembly."""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', 'svml_z0_atanh_d_ha.s')
vec = extract(S, '__svml_datanh_ha_data_internal_avx512')
cout = extract(S, '__datanh_ha_CoutTab')
hx = lambda q: as_double(q).hex() if (q >> 52) & 0x7ff != 0x7ff else None

def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]

print('/* generated by functions/atanh/tools/gen_svml_constants.py from svml_z0_atanh_d_ha.s */')
print('/* vector path (__svml_datanh_ha_data_internal_avx512) */')
print('static const double kLogTh[16] = {  /* log(1 + k/16), high part (k = top 4 mantissa bits of Rcp) */')
for j in range(16): print(f'    {hx(vec[j])},')
print('};')
print('static const double kLogTl[16] = {  /* low part */')
for j in range(16): print(f'    {hx(vec[16 + j])},')
print('};')
dbl = [(256, 'kOne', '|x| >= 1 or NaN: scalar callout'),
       (512, 'kLogC9', 'log(1+R) = R + R^2*(C1 + C2 R + ... + C9 R^8)'), (576, 'kLogC8', ''), (640, 'kLogC7', ''),
       (704, 'kLogC6', ''), (768, 'kLogC5', ''), (832, 'kLogC4', ''), (896, 'kLogC3', ''), (960, 'kLogC2', ''),
       (1024, 'kLogC1', ''), (1088, 'kL2H', 'ln2 = L2H + L2L'), (1152, 'kL2L', ''), (1216, 'kHalf', '')]
for off, name, comment in dbl:
    c = f'  /* {comment} */' if comment else ''
    print(f'static const double {name} = {hx(lane(off))};{c}')
for off, name, comment in [(320, 'kAbsMask', ''), (384, 'kRcpRoundAdd', 'Rcp: rcp14 rounded to 1+4 mantissa bits'),
                           (448, 'kRcpRoundMask', '')]:
    c = f'  /* {comment} */' if comment else ''
    print(f'static const uint64_t {name} = 0x{lane(off):016x}ULL;{c}')
print('\n/* scalar callout (__datanh_ha_CoutTab) */')
print('static const double kCoutTab[4] = {', ', '.join(hx(q) or ('INFINITY' if q >> 63 == 0 else '-INFINITY') for q in cout), '};')
