"""Print C declarations for the atan_d_ha vector-path constants, taken bit-exactly from the SVML assembly.
(The scalar callout and its table are translated by functions/asin/tools/asm2c.py.)"""
import os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'common', 'tools'))
from extract_tables import extract, as_double

S = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'third_party', 'SVML', 'linux', 'avx512', 'svml_z0_atan_d_ha.s')
vec = extract(S, '__svml_datan_ha_data_internal_avx512')

def lane(off):  # 64-byte block of 8 identical lanes
    words = vec[off // 8: off // 8 + 8]
    assert len(set(words)) == 1, off
    return words[0]

print('/* Generated by tools/gen_svml_constants.py from svml_z0_atan_d_ha.s (__svml_datan_ha_data_internal_avx512); do not edit. */')
print('static const double vAtanHi[32] = {  /* atan(j/4) = AtanHi[j] + AtanLo[j], j = 0..31 */')
for j in range(32): print(f'    {as_double(vec[56 + j]).hex()},')
print('};')
print('static const double vAtanLo[32] = {')
for j in range(32): print(f'    {as_double(vec[88 + j]).hex()},')
print('};')
for off, name, what in [
        (64, 'vShifter', '1.5*2^50: RN(|x| + Shifter) rounds |x| to a multiple of 1/4, j in the low mantissa bits'),
        (128, 'vTabMax', '|x| < 7.875: table path, else atan(|x|) = pi/2 + atan(-1/|x|)'),
        (192, 'vMOne', '-1.0: Diff for large |x|'), (256, 'vOne', '1.0'),
        (320, 'vYMax', '2^128: Y = min(|x|, 2^128) for large |x|'), (960, 'vShifter16', 'Shifter + 4: j >= 16'),
        (1024, 'vPio2Hi', 'pi/2 = Pio2Hi + Pio2Lo'), (1088, 'vPio2Lo', ''),
        (1152, 'vA5', 'atan(R) = R + R^3*(A0 + A1 R^2 + ... + A5 R^10)'), (1216, 'vA4', ''), (1280, 'vA3', ''),
        (1344, 'vA2', ''), (1408, 'vA1', ''), (1472, 'vA0', '')]:
    q = lane(off)
    print(f'#define {name:<10} {as_double(q).hex():<26}/* {what} */' if what else f'#define {name:<10} {as_double(q).hex()}')
print(f'#define vAbsMaskBits 0x{lane(0):016x}ULL')
